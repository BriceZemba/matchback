export const LOCALES = ["en", "fr", "es"] as const;
export type Locale = (typeof LOCALES)[number];

export function toLocale(v: string | null | undefined): Locale | null {
  const two = (v ?? "").toLowerCase().slice(0, 2);
  return (LOCALES as readonly string[]).includes(two) ? (two as Locale) : null;
}

/** Cookie first, then the browser's Accept-Language, then English. */
export function pickLocale(cookie: string | undefined, acceptLanguage: string | null): Locale {
  const fromCookie = toLocale(cookie);
  if (fromCookie) return fromCookie;
  for (const part of (acceptLanguage ?? "").split(",")) {
    const l = toLocale(part.trim());
    if (l) return l;
  }
  return "en";
}

/** One cookie from a raw request (route handlers that only have the Request). */
export function cookieValue(req: Request, name: string): string | undefined {
  for (const part of (req.headers.get("cookie") ?? "").split(";")) {
    const [k, ...v] = part.trim().split("=");
    if (k === name) return decodeURIComponent(v.join("="));
  }
  return undefined;
}

