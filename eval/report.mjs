// Builds eval/results.md from the JSON files written by `npm run eval` (whichever exist).
// Usage: node eval/report.mjs
//
// Files and what they are:
//   results-dev-v1.json      development set, identity prompt v1
//   results-dev.json         development set, final version (v2)
//   results-heldout-v1.json  held-out set 1, v1 — its first and only blind look
//   results-heldout.json     held-out set 1, v2 — a second look (the set had already been seen once)
//   results-heldout2.json    held-out set 2, v2 — first look, collected before v2 was written
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const FACT = new Set(["stock", "cheaper", "floor", "window"]);
const grade = (c, r) => {
  if (r.decision === "needs_review") return "manual";
  if (!c.legit) return r.decision === "approved" ? "unsafe" : "correct";
  if (r.decision === "approved") return "correct";
  const failed = r.notPassed.filter((n) => n.includes(": fail")).map((n) => n.split(":")[0]);
  return failed.length && failed.every((id) => FACT.has(id)) ? "correct" : "missed";
};
const usd = (c) => (c === null || c === undefined ? "—" : `$${(c / 100).toFixed(2)}`);
const SYS = ["matchback", "id_only", "naive"];
const LABEL = { matchback: "Matchback (rules + AI identity)", id_only: "Same rules, Channel3 id only", naive: "Naive: approve if cheaper" };
const load = (name) => (existsSync(`eval/${name}`) ? JSON.parse(readFileSync(`eval/${name}`, "utf8")) : null);
const HEAD = "| System | Correct | Sent to a person | Unsafe payouts | Money wrongly refunded | Missed legit | Legit claims paid automatically |\n|---|---|---|---|---|---|---|";

function totals(rows, s) {
  const g = rows.map((r) => ({ r, g: grade(r.case, r.results[s]) }));
  const n = (k) => g.filter((x) => x.g === k).length;
  const unsafe = g.filter((x) => x.g === "unsafe");
  const legit = rows.filter((r) => r.case.legit);
  return {
    correct: n("correct"), manual: n("manual"), unsafe: unsafe.length, missed: n("missed"),
    dollars: unsafe.reduce((t, x) => t + x.r.results[s].refundCents, 0) / 100,
    legitPaid: legit.filter((r) => r.results[s].decision === "approved").length,
    legit: legit.length, traps: rows.length - legit.length, cases: rows.length,
  };
}
const line = (label, t) => `| ${label} | ${t.correct}/${t.cases} | ${t.manual} | ${t.unsafe} of ${t.traps} traps | $${t.dollars.toFixed(2)} | ${t.missed} | ${t.legitPaid}/${t.legit} |`;

const out = [];
out.push("# Evaluation results", "");
out.push("Generated by `node eval/report.mjs` from the JSON files written by `npm run eval` (see `eval/README.md`).", "");
out.push("**Grades.** *correct*: a trap refused, or a legitimate claim paid (or refused only because of a fact: out of stock, not cheaper, implausibly cheap, outside the window). *manual*: sent to a person. *unsafe*: a claim that should not be paid was paid. *missed*: a legitimate claim refused for a non-factual reason.", "");

const dev = load("results-dev.json");
const devV1 = load("results-dev-v1.json");
const ho1v1 = load("results-heldout-v1.json");
const ho1v2 = load("results-heldout.json");
const ho2 = load("results-heldout2.json");

// Final version over every case it has been run on.
const finalSets = [dev, ho1v2, ho2].filter(Boolean);
if (finalSets.length) {
  const rows = finalSets.flatMap((d) => d.rows);
  out.push(`## Final version, all ${rows.length} cases`, "");
  out.push("Development set + held-out set 1 (second look) + held-out set 2 (first look).", "");
  out.push(HEAD);
  for (const s of SYS) out.push(line(LABEL[s], totals(rows, s)));
  const manual = rows.filter((r) => r.results.matchback.decision === "needs_review");
  out.push("", `Of the ${manual.length} claims Matchback sent to a person, ${manual.filter((r) => r.lookupError).length} were pages Channel3 could not read (${rows.filter((r) => r.lookupError).length} lookup failures in total) and ${manual.filter((r) => !r.lookupError).length} lacked a stated condition or a confident identity.`, "");
}

// Blind results only: each held-out set the first time it was run.
if (ho1v1 || ho2) {
  out.push("## First-look held-out results (the honest generalisation numbers)", "");
  out.push("Each row is a held-out set the first and only time it was run blind.", "");
  out.push("| Set | Version | Cases | Matchback unsafe | Matchback missed | Matchback sent to a person | Naive unsafe | Naive money wrongly refunded |", "|---|---|---|---|---|---|---|---|");
  for (const [name, ver, d] of [["Held-out 1", "v1", ho1v1], ["Held-out 2", "v2 (final)", ho2]]) {
    if (!d) continue;
    const m = totals(d.rows, "matchback");
    const nv = totals(d.rows, "naive");
    out.push(`| ${name} | ${ver} | ${d.rows.length} | ${m.unsafe} of ${m.traps} | ${m.missed} | ${m.manual} | ${nv.unsafe} of ${nv.traps} | $${nv.dollars.toFixed(2)} |`);
  }
  out.push("");
}

// What changed between the two identity prompts, on the development set.
if (devV1 && dev) {
  out.push("## Development set: identity prompt v1 → v2", "");
  out.push("| Version | Correct | Sent to a person | Unsafe payouts | Money wrongly refunded | Missed legit | Legit claims paid automatically |", "|---|---|---|---|---|---|---|");
  out.push(line("v1", totals(devV1.rows, "matchback")));
  out.push(line("v2 (final)", totals(dev.rows, "matchback")));
  const before = Object.fromEntries(devV1.rows.map((r) => [r.case.id, r]));
  const changed = dev.rows.filter((r) => before[r.case.id] && (before[r.case.id].results.matchback.decision !== r.results.matchback.decision || before[r.case.id].relation !== r.relation));
  out.push("", changed.length ? "Cases whose AI relation or decision changed:" : "No case changed.", "");
  for (const r of changed) {
    const a = before[r.case.id];
    out.push(`- **${r.case.id}** (${r.case.legit ? "legit" : "trap"}: ${r.case.why}): ${a.relation ?? "—"} → ${r.relation ?? "—"}; ${a.results.matchback.decision} → ${r.results.matchback.decision}`);
  }
  out.push("");
}

const sections = [
  [dev, "Development set (final version)"],
  [ho2, "Held-out set 2 (final version, first look)"],
  [ho1v2, "Held-out set 1 (final version, second look — this set was already run once with v1)"],
  [ho1v1, "Held-out set 1 (version 1, first look)"],
];
for (const [data, title] of sections) {
  if (!data) continue;
  out.push(`## ${title}`, "");
  out.push(`Run ${data.ranAt}, Channel3 cache mode \`${data.cache}\`, ${data.rows.length} cases.`, "");
  out.push(HEAD);
  for (const s of SYS) out.push(line(LABEL[s], totals(data.rows, s)));
  out.push("");
  out.push("| Case | Kind | Legit | Paid | Competitor | Condition (source) | Stock | AI relation | Matchback | Id only | Naive |", "|---|---|---|---|---|---|---|---|---|---|---|");
  for (const r of data.rows) {
    const cell = (s) => `${r.results[s].decision}${grade(r.case, r.results[s]) === "correct" ? "" : ` (${grade(r.case, r.results[s])})`}`;
    out.push(`| ${r.case.id} | ${r.case.kind} | ${r.case.legit ? "yes" : "no"} | ${usd(r.paidCents)} | ${usd(r.competitorCents)} | ${r.condition ?? "none"} (${r.conditionSource ?? "—"}) | ${r.availability ?? "—"} | ${r.relation ?? "—"} | ${cell("matchback")} | ${cell("id_only")} | ${cell("naive")} |`);
  }
  out.push("", "### Matchback cases that were not graded correct", "");
  const bad = data.rows.filter((r) => grade(r.case, r.results.matchback) !== "correct");
  if (!bad.length) out.push("None.");
  for (const r of bad) {
    out.push(`- **${r.case.id}** (${r.case.why}; legit: ${r.case.legit ? "yes" : "no"}) → ${r.results.matchback.decision}, grade ${grade(r.case, r.results.matchback)}. AI relation: ${r.relation ?? "—"}. Checks not passed: ${r.results.matchback.notPassed.join(", ") || "none"}.${r.lookupError ? ` Lookup: ${r.lookupError}` : ""}`);
  }
  out.push("");
}
writeFileSync("eval/results.md", out.join("\n"));
console.log("wrote eval/results.md");
